package pl.psnc.vtl.portal.model.verses;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnore;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.GenericGenerator;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;
import org.hibernate.annotations.Parameter;
import pl.psnc.vtl.portal.conf.datetime.ApiDateTimeFormatter;
import pl.psnc.vtl.portal.model.users.User;
import pl.psnc.vtl.portal.services.verses.VerseContentService;
import pl.psnc.vtl.portal.utils.HTMLParser;

import javax.persistence.*;
import java.time.LocalDateTime;

/**
 * Content of the verse
 */
@Data
@AllArgsConstructor
@NoArgsConstructor
@Entity
//TODO: unique key
//@Table(name = "verse_contents", uniqueConstraints = {
//        @UniqueConstraint(columnNames = {"user_id", "update_date", "verse_id"})})
@Table(name = "verse_contents")
@EqualsAndHashCode(exclude = {"verse"})
public class VerseContent {

    //TODO: calc leven.. distance
    public VerseContent(User user, Verse verse, String content) {
        this.user = user;
        this.verse = verse;
        this.updateDate = LocalDateTime.now();
        this.content = content;
        this.init();
    }


    public VerseContent(Long id, User user, Verse verse, String content) {
        this.id = id;
        this.user = user;
        this.verse = verse;
        this.updateDate = LocalDateTime.now();
        this.content = content;
        this.init();
    }


    public VerseContent(User user, Verse verse, String content, boolean isFromOCR) {
        this.user = user;
        this.verse = verse;
        this.content = content;
        this.updateDate = LocalDateTime.now();
        this.isFromOCR = isFromOCR;
        this.init();
    }

    private void init() {
        this.oldContent = this.verse.getCurrentVerseContent();
        if (oldContent != null && oldContent.rejectedBy == null) {
            oldContent.rejectedBy = user;
        }
        if (this.oldContent != null)
            this.distance = VerseContentService.distance.apply(this.oldContent.getContent(), this.content);
    }


    //TODO: verify on delete cascade user and verse
    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "verse_contents_generator")
    @GenericGenerator(name = "verse_contents_generator",
            strategy = "pl.psnc.vtl.portal.repositories.persistence.RestorableSequenceGenerator",
            parameters = { @Parameter(name = "sequence_name", value = "verse_contents_id_seq") })
    private Long id;

    /**
     * User that is author of the content.
     */
    @ManyToOne(optional = true, fetch = FetchType.LAZY, cascade = CascadeType.REFRESH)
    @OnDelete(action = OnDeleteAction.CASCADE)
    @JoinColumn(name = "user_id")
    private User user;

    /**
     * Verse that this content belongs to.
     */
    @OnDelete(action = OnDeleteAction.CASCADE)
    @ManyToOne(optional = false, fetch = FetchType.LAZY, cascade = CascadeType.REFRESH)
    @JoinColumn(name = "verse_id")
    @JsonIgnore
    private Verse verse;

    /**
     * Content text.
     */
    @Column(nullable = false, length = 4096)
    private String content;

    /**
     * Content text in plain format.
     */
    @Column(nullable = false, length = 4096)
    private String plainContent;

    /**
     * Previous content.
     */
    @OneToOne(optional = true, fetch = FetchType.LAZY, cascade = CascadeType.REFRESH)
    @JoinColumn(name = "old_verse_id")
    @JsonIgnore
    private VerseContent oldContent;

    /**
     * Tells if content was generated by OCR process.
     */
    @Basic
    @Column(nullable = false, columnDefinition = "boolean default false")
    private boolean isFromOCR = false;

    /**
     * Is this content initial for its verse.
     */
    @Basic
    @Column(nullable = false, columnDefinition = "boolean default false")
    private boolean isInitial = false;

    /**
     * Date of last content modification.
     */
    @Basic
    @Column(nullable = true)    //TODO: make nonnullable and set auto timestamp
    @CreationTimestamp
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = ApiDateTimeFormatter.dateTimePattern)
    private LocalDateTime updateDate;

    /**
     * Tells which user rejected this content.
     */
    @ManyToOne(optional = true, fetch = FetchType.LAZY, cascade = CascadeType.REFRESH)
    @JoinColumn(name = "rejected_by_user_id")
    private User rejectedBy;

    /**
     * Distance between new content and old content.
     */
    @Basic
    @Column(nullable = true)
    private Integer distance;

    @PrePersist
    @PreUpdate
    public void removeWhitespace() {
        this.plainContent = this.content != null ? HTMLParser.plainText(this.content) : null;
    }
}
